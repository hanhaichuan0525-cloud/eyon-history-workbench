        - 交代当时正在发生什么，前事留下了什么不同，为什么这个关口会在此时出现，不只依靠然后、后来、于是串联无关事件
    转向:
      具体事件:
        - 写出谁或什么作出回应，遭遇哪件事，采取什么行动，不用受到影响、局势变化代替事情发生
        - 人物有自己的愿望、处境、知识与判断，环境或事件主导时写其实际变化，不硬加人物中转
