        - 写清与直接延续相比，目标、承担者、关系、用途、机会、位置、局势或环境怎样不同
        - 转折可以很小，但要影响后事，不能只增加热闹或用局势因此改变略去关键变化
        - 成名、繁荣、制度形成与格局重塑是结果，须有使这些结果成立的事情
        - 转折不等于反转，平静的决定、一次成功、一次拒绝或一次错过同样能够改变历史
    启后:
      留给后事的条件:
        - 写清解决了什么、又打开什么可能，谁因此获得机会、被迫另作选择，或原有进程怎样不同
        - 下一段回应这一新处境，不必再次回到玩家最初的行为、原物或原主角
        - 原物、原句、原名字与原主角可以消失，已经改变的条件仍能推动后来历史
    表达分寸:
      - 承接、事件、转向、启后是组织要点，不要求每次写成四段，不把正文变成分析表或任务流程
      - 一个紧凑场面或几句叙事也能完成承前、转向、启后，详写关键关口，普通连接可以压缩
