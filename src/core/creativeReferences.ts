export function ruinStyleMeaning(group: keyof typeof RUIN_STYLE_OPTIONS, value: string): string {
  const option = RUIN_STYLE_OPTIONS[group].find(option => option === value) ?? '随内容自动';
  const [meaning, ...craft] = (RUIN_STYLE_MEANINGS[group] as Record<string, string>)[option].split('。').filter(Boolean);
  return [`含义: ${meaning}`, `写法: ${craft.join('；')}`].join('\n');
}

export function renderRuinStyleReminder(input: RuinGenerationInput): string {
  const refs = input.creativeReferences ?? defaultRuinReferences(input.materials.map(item => item.periodType));
  const line = (group: keyof typeof RUIN_STYLE_OPTIONS) => {
    const option = RUIN_STYLE_OPTIONS[group].find(option => option === refs[group]) ?? '随内容自动';
    return `「${ruinStyleLabel(group, option)}」：${ruinStyleMeaning(group, option).split('\n')[0].replace(/^含义: /u, '')}`;
  };
  return [
    '<RUIN_STYLE_REMINDER>',
    '本轮讲述气质回看：在既定事实与四阶段中体现这些表达偏好，无需输出说明、评分或新字段。',
    ...(['telling', 'pace', 'mood'] as const).map(line),
    '</RUIN_STYLE_REMINDER>',
  ].join('\n');
}

